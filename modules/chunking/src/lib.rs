#[cfg(test)]
mod tests {
    use super::{POLICIES, claiming, names};

    #[test]
    fn every_policy_has_a_name_of_its_own() {
        let mut seen: Vec<&str> = names().collect();
        let count = seen.len();

        // The build refuses a duplicate, so this is the check on the *build*: a table that lost that
        // refusal would let a store's answer depend on the order of this list.
        seen.sort_unstable();
        seen.dedup();

        assert_eq!(seen.len(), count);
    }

    #[test]
    fn one_container_is_claimed_by_one_policy() {
        let mut claims: Vec<&str> = POLICIES
            .iter()
            .flat_map(|policy| policy.extensions.iter().copied())
            .collect();
        let count = claims.len();

        claims.sort_unstable();
        claims.dedup();

        assert_eq!(claims.len(), count);
    }

    #[test]
    fn every_name_is_kebab_case() {
        for name in names() {
            assert!(
                !name.is_empty()
                    && name.split('-').all(|word| {
                        !word.is_empty()
                            && word.chars().all(|character| {
                                character.is_ascii_lowercase() || character.is_ascii_digit()
                            })
                    }),
                "`{name}` is not kebab-case"
            );
        }
    }

    #[test]
    fn a_container_that_is_named_is_the_policy_that_claims_it() {
        for policy in POLICIES {
            for extension in policy.extensions {
                let claimed = claiming(extension).expect("an extension the table holds is claimed");

                assert_eq!(claimed.name, policy.name, "`{extension}`");
            }
        }
    }
}
