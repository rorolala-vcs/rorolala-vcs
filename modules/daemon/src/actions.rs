use std::net::SocketAddr;

use rorolala_protocol::{Action, ActionContext, ActionError, OnlyWorkspace, Socket};
use tokio::net::TcpStream;

use rorolala_auth::{Account, SecureStream};
use rorolala_errors::AddrError;

use crate::wire;

/// Runs the action `A` on `input`, as `account`, against the daemon at `target`.
///
/// The input is what the caller asked for, so it belongs to the Workspace side and is
/// wrapped as the [`OnlyWorkspace`] the action takes; the account is the one the caller
/// named, so the action runs as that identity rather than as whatever was found first; and
/// `target` is the daemon to reach, as an ip and a port.
///
/// The session is established before the action runs. The account's private key proves
/// which identity the action runs as, and a public key beside it — if there is one — is
/// the identity the peer must prove in turn. An account without one accepts the peer as
/// whoever it proves itself to be, which is what lets a Workspace that knows only its own
/// key still be challenged by a Vault.
///
/// # Errors
///
/// Returns [`ActionError::Addr`] if `target` is not an ip and a port,
/// [`ActionError::Auth`] if a key cannot be read or the peer cannot be proven, and
/// [`ActionError`] once the action can be carried out but the exchange fails.
pub async fn proc_action<A>(
    account: &Account,
    target: String,
    input: A::Input,
) -> Result<A::Output, ActionError>
where
    A: Action,
{
    // Read before anything else: an address that cannot be one is the caller's to fix, and
    // says so here rather than at the first write.
    let address: SocketAddr = target
        .parse()
        .map_err(|_| ActionError::Addr(AddrError::new(target)))?;

    let identity = account.get_key()?;
    let expected = account.peer_key()?;

    // Prove who the action runs as, and hold the peer to an identity where the account
    // says which one that must be.
    let socket: Box<dyn Socket> = Box::new(TcpStream::connect(address).await?);
    let mut channel = match &expected {
        Some(expected) => SecureStream::connect(socket, &identity, expected).await?,
        None => SecureStream::connect_unpinned(socket, &identity).await?,
    };

    // Name the action and the account we act as, and wait for the peer to say it read the
    // same request. An id the peer does not answer for never starts an action.
    wire::write_request(
        &mut channel,
        &wire::Request {
            id: A::ID,
            account: account.name(),
        },
    )
    .await?;

    if wire::read_confirmation(&mut channel).await? != wire::confirmation(A::ID) {
        return Err(ActionError::UnknownAction(A::ID));
    }

    let input = OnlyWorkspace::from(Some(input));
    let ctx = ActionContext::new_workspace_ctx(account.clone()).with_channel(channel);

    A::process(input, ctx).await
}

