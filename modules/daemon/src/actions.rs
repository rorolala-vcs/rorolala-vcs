#[cfg(test)]
mod tests {
    use rorolala_auth::Account;
    use rorolala_protocol::{ActionContext, ActionError};

    use super::{build_action_registry, do_action_with};

    /// An id no action claims is refused rather than mistaken for a position.
    ///
    /// Ids name actions: they are the one thing a caller outside Rust holds onto, so a
    /// list that skipped some would still reach the ones it has, and an id that names
    /// nothing is an error. `u32::MAX` is the id no action is ever given.
    #[tokio::test]
    async fn an_id_no_action_names_is_an_error() {
        let registry = build_action_registry();
        let ctx = ActionContext::new_workspace_ctx(Account::default());

        let error = do_action_with(&registry, u32::MAX, ctx)
            .await
            .expect_err("an id no action names is refused");

        assert!(matches!(error, ActionError::UnknownAction(id) if id == u32::MAX));
    }
}
