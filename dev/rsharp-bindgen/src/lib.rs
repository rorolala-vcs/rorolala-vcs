//! Generates the C# bindings for Rorolala's C ABI, from the C header `rorolala-dev-bindgen` writes.
//!
//! The input is the header, not the Rust sources: what a C# caller may name is exactly what the
//! header declares, so reading it is what keeps the two surfaces the same one. A C# project
//! (`RolaSharp`) runs this on every build, so its bindings are never stale against the header.
//!
//! # What is generated
//!
//! A free function becomes a `[DllImport]` extern on `RolaSharp.RorolalaBinding`, a named enum
//! becomes a C# enum, and a complete struct or union becomes a `[StructLayout]` struct — a union an
//! explicit layout. Every pointer becomes a `nint`, because the header cannot say what a pointer
//! points at and the layer above owns the marshalling: a returned string is a pointer to release
//! with `free_string`. Every member is `internal`, so the assembly's public shape is empty and the
//! hand-written, more OOP layer is what a caller sees.
//!
//! A name the header only forward-declares is not emitted — it can only cross as a pointer, and
//! every pointer is a `nint`. A type held **by value** is looked up in the header, and an opaque one
//! there is refused, since C could not lay it out either.

